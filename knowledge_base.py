def render_chapter(chapter: dict) -> str:
    """将章节数据渲染为Markdown"""
    lines = [f"## {chapter['title']}\n"]

    lines.append("### 核心概念\n")
    for c in chapter["core"]:
        lines.append(f"- {c}")
    lines.append("")

    lines.append("### 关键公式\n")
    for f in chapter["formulas"]:
        lines.append(f"- `{f}`")
    lines.append("")

    lines.append("### 解题方法\n")
    for m in chapter["methods"]:
        lines.append(f"- {m}")
    lines.append("")

    lines.append("### 常见错误\n")
    for p in chapter["pitfalls"]:
        lines.append(f"- ⚠️ {p}")
    lines.append("")

    return "\n".join(lines)


def render_course(course: dict) -> str:
    """将课程数据渲染为完整Markdown"""
    lines = [f"# {course['icon']} {course['name']}\n"]
    lines.append(f"> {course['desc']}\n")
    for ch in course["chapters"]:
        lines.append(render_chapter(ch))
    return "\n".join(lines)
